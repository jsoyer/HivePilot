# ---------------------------------------------------------------------------
# Never ship a real-looking secret in a committed example file.
# ---------------------------------------------------------------------------

_SUSPICIOUS_SECRET_PATTERNS = (
    re.compile(r"xox[baprs]-[0-9A-Za-z-]{10,}"),  # real Slack token shape
    re.compile(r"xapp-[0-9A-Za-z-]{10,}"),  # real Slack app token shape
    re.compile(r"\b\d{17,20}\.[\w-]{6,}\.[\w-]{20,}\b"),  # real Discord bot token shape
)


def test_conf_d_examples_contain_no_real_looking_secrets():
    for path in CONFD_DIR.glob("*.example"):
        content = path.read_text()
        for pattern in _SUSPICIOUS_SECRET_PATTERNS:
            assert not pattern.search(content), f"{path} looks like it contains a real secret"
